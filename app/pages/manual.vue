      <p class="doc-p">为进一步加强宗教团体和宗教活动场所规范化、法治化建设，切实维护宗教团体和宗教活动场所的权益，完善信息财务公开和民主管理，让信教群众真正享有知情权、监督权。在当前规范化管理的基础上，开发互联网信息公开系统，实现宗教团体和宗教活动场所信息财务规范公开透明。</p>

      <h2 class="doc-h">二、系统建设目标</h2>
      <p class="doc-p">1.实现全县宗教场所信息公开的维护管理</p>
