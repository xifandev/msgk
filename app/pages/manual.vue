      <p class="doc-p">1.各活动场所的管理员</p>
      <p class="doc-p">主要负责录入该场所的公开信息，每月定期上传财务收支情况，并提交审核。</p>
      <p class="doc-p">2.乡镇管理员</p>
      <p class="doc-p">主要负责审核场所上报的公开信息和财务收支情况</p>
      <p class="doc-p">3.县级管理员</p>
      <p class="doc-p">主要负责审核乡镇审查的公开信息和财务收支情况，发布法律法规和通知公告</p>

      <h2 class="doc-h">五、录入场所介绍</h2>
      <p class="doc-p">1.首先在导航栏，打开“场所介绍”栏目</p>
      <p class="doc-p">2.填写场所信息，想公开更多可点击“添加更多”</p>
      <p class="doc-p">3.录入完成后点击“提交审核”</p>
      <p class="doc-p">4.乡镇、县里审核通过后即可公开展示</p>
      <p class="doc-p">5.提交审核后再次编辑需点击“重新编辑”</p>

      <h2 class="doc-h">六、录入人员公开</h2>
      <p class="doc-p">1.首先在导航栏，打开“人员公开”栏目</p>
      <p class="doc-p">2.选择“添加人员”，填写人员信息，主要包括：</p>
      <p class="doc-p">（一）场所负责人</p>
      <p class="doc-p">（二）教职人员</p>
      <p class="doc-p">（三）民主管理组织成员</p>
      <p class="doc-p">（四）财务管理组织出纳、会计、资产管理</p>
      <p class="doc-p">（五）安全生产管理</p>
      <p class="doc-p">点击“确认”</p>
      <p class="doc-p">3.点击“编辑”可修改人员信息</p>
      <p class="doc-p">4.乡镇、县里审核通过后即可公开展示</p>
      <p class="doc-p">5.提交审核后再次编辑需点击“重新编辑”</p>

      <h2 class="doc-h">七、录入场所安全动态</h2>
      <p class="doc-p">主要包括消防、用电、房屋安全、饮食、活动安全等方面。县里统一发布。</p>

      <h2 class="doc-h">八、录入财务公开</h2>
      <p class="doc-p">1.首先在导航栏，打开“财务公开”栏目</p>
      <p class="doc-p">2.选择“添加月度公开”，选择相应月份，点击“确定”</p>
      <p class="doc-p">3.点击“录入明细”“添加收支”填写收支数据</p>
      <p class="doc-p">4.录入完成后点击“关闭并保存”</p>
      <p class="doc-p">5.当月数据录入完毕后，请点击“提交审核”</p>
      <p class="doc-p">6.乡镇、县里审核通过后即可公开展示</p>
      <p class="doc-p">7.提交审核后如需修改，须点击“查看审核”“重新编辑”</p>
      <h3 class="doc-h3">随时随地快速录入收支情况：</h3>
      <p class="doc-p">在“码上公开”小程序的顶部找到“场所管理”栏目，进行手机号安全验证，验证通过后，可快速录入该场所收支情况。主要是快速录入收支情况，用手机直接操作就可以，不需要再用电脑录入。</p>

      <h2 class="doc-h">九、查看场所二维码</h2>
      <p class="doc-p">点击场所二维码打开，点击鼠标右键保存场所专属二维码图片，可自行打印张贴，方便信众扫码查看公开信息。</p>

      <h2 class="doc-h">十、政策法规栏目</h2>
      <p class="doc-p">由县级管理员统一上传有关法律法规。</p>

      <h2 class="doc-h">十一、最新公告栏目</h2>
      <p class="doc-p">由县级管理员负责公告的发布。</p>

